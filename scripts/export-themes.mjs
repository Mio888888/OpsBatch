#!/usr/bin/env node
// Generate crates/ops-core/src/theme/data.rs from OpsBatch's src/data/themes.ts (14 terminal/UI themes, 13 accents).
// usage: node scripts/export-themes.mjs [path/to/OpsBatch]
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.argv[2] ?? path.resolve(import.meta.dirname, '../../OpsBatch');
const mod = await import(pathToFileURL(path.join(root, 'src/data/themes.ts')).href);
const q = (s) => JSON.stringify(s);
const XTERM_KEYS = ['background', 'foreground', 'cursor', 'selectionBackground', 'black', 'red', 'green', 'yellow', 'blue',
  'magenta', 'cyan', 'white', 'brightBlack', 'brightRed', 'brightGreen', 'brightYellow', 'brightBlue', 'brightMagenta',
  'brightCyan', 'brightWhite'];
const UI_KEYS = ['pageBg', 'sidebarBg', 'mainBg', 'cardBg', 'headerBg', 'border', 'borderStrong', 'inputBg', 'inputBorder', 'navHover'];
const PREVIEW_KEYS = ['background', 'lineStrong', 'lineMedium', 'lineWeak', 'accent'];

let out = '// @generated by scripts/export-themes.mjs from OpsBatch src/data/themes.ts — do not edit by hand.\n\n';
out += 'use super::{Accent, TerminalPalette, ThemeDef, ThemeTone, UiPalette, PreviewPalette};\n\n';
out += 'pub static THEMES: &[ThemeDef] = &[\n';
for (const t of mod.allThemes) {
  for (const k of XTERM_KEYS) if (!t.xterm[k]) throw new Error(`${t.id} missing xterm.${k}`);
  out += `    ThemeDef {\n        id: ${q(t.id)},\n        name: ${q(t.name)},\n        tone: ThemeTone::${t.tone === 'dark' ? 'Dark' : 'Light'},\n`;
  out += `        preview: PreviewPalette { ${PREVIEW_KEYS.map((k) => `${snake(k)}: ${q(t.preview[k])}`).join(', ')} },\n`;
  out += `        ui: UiPalette { ${UI_KEYS.map((k) => `${snake(k)}: ${q(t.ui[k])}`).join(', ')} },\n`;
  out += `        terminal: TerminalPalette { ${XTERM_KEYS.map((k) => `${snake(k)}: ${q(t.xterm[k])}`).join(', ')} },\n    },\n`;
}
out += '];\n\npub static ACCENTS: &[Accent] = &[\n';
for (const a of mod.accentColors) out += `    Accent { id: ${q(a.id)}, name: ${q(a.name)}, base: ${q(a.base)}, strong: ${q(a.strong)} },\n`;
out += '];\n';
function snake(s) { return s.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase()); }
fs.writeFileSync(path.resolve(import.meta.dirname, '../crates/ops-core/src/theme/data.rs'), out);
console.log(mod.allThemes.length, 'themes,', mod.accentColors.length, 'accents');
